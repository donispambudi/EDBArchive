#!/usr/bin/env bash

set -euo pipefail

usage() {
    cat <<'EOF'
Usage: benchmark.sh scenarios [options]

Optional:
  --run-id NAME         result group and database suffix (default: UTC timestamp)
  --source-db NAME      source database (default: tpcc)
  --scenario NAME       all, district, or district-customer-item (default: all)
  --context FILE        existing context.bin
  --key-dir DIR         directory containing existing public.bin and private.bin
  --keep-databases      retain successfully restored benchmark databases

The defaults use the context and key pair generated by DatabaseSeeder in the
main EDBArchive storage volume.
EOF
}

run_id="run_$(date -u +%Y%m%dT%H%M%SZ)"
source_db="tpcc"
selected_scenario="all"
context_file="/edbarchive-storage/private/1/context.bin"
key_directory="/edbarchive-storage/private/2"
keep_databases=0

while (($#)); do
    case "$1" in
        --run-id) run_id="${2:?missing value for --run-id}"; shift 2 ;;
        --source-db) source_db="${2:?missing value for --source-db}"; shift 2 ;;
        --scenario) selected_scenario="${2:?missing value for --scenario}"; shift 2 ;;
        --context) context_file="${2:?missing value for --context}"; shift 2 ;;
        --key-dir) key_directory="${2:?missing value for --key-dir}"; shift 2 ;;
        --keep-databases) keep_databases=1; shift ;;
        --help|-h) usage; exit 0 ;;
        *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
    esac
done

if [[ ! "${run_id}" =~ ^[A-Za-z0-9_]+$ ]]; then
    echo "--run-id may contain only letters, numbers, and underscores." >&2
    exit 2
fi
if [[ ! "${source_db}" =~ ^[A-Za-z0-9_]+$ ]]; then
    echo "Unsafe source database name: ${source_db}" >&2
    exit 2
fi
case "${selected_scenario}" in
    all|district|district-customer-item) ;;
    *) echo "Invalid --scenario: ${selected_scenario}" >&2; exit 2 ;;
esac
for path in "${context_file}" "${key_directory}/public.bin" "${key_directory}/private.bin"; do
    [[ -f "${path}" ]] || { echo "Required FHE artifact not found: ${path}" >&2; exit 2; }
done

temporary_root="${BENCHMARK_TEMP_DIR:-/tmp}"
mkdir -p "${temporary_root}"
[[ -d "${temporary_root}" && -w "${temporary_root}" ]] || {
    echo "Benchmark temporary directory is not writable: ${temporary_root}" >&2
    exit 2
}

if [[ "${selected_scenario}" != "district" ]]; then
    minimum_free_bytes=$((65 * 1024 * 1024 * 1024))
    recommended_free_bytes=$((minimum_free_bytes * 3 / 2))
    available_bytes="$(df -PB1 "${temporary_root}" | awk 'NR == 2 {print $4}')"
    if [[ ! "${available_bytes}" =~ ^[0-9]+$ ]]; then
        echo "Cannot determine free space for ${temporary_root}." >&2
        exit 2
    fi

    available_gib=$((available_bytes / 1024 / 1024 / 1024))
    if ((available_bytes < minimum_free_bytes)); then
        echo "Insufficient temporary storage for the large benchmark scenario." >&2
        echo "Available: ${available_gib} GiB; required minimum: 65 GiB." >&2
        echo "Set BENCHMARK_TMP_DIR to a directory on a larger drive." >&2
        exit 2
    fi
    if ((available_bytes < recommended_free_bytes)); then
        echo "WARNING: only ${available_gib} GiB is available on ${temporary_root}." >&2
        echo "The recommended free space is 97.5 GiB (65 GiB x 1.5)." >&2
    fi
fi

db_host="${BENCHMARK_DB_HOST:-mariadb}"
db_port="${BENCHMARK_DB_PORT:-3306}"
db_user="${BENCHMARK_DB_USER:-edbarchive}"
export MYSQL_PWD="${BENCHMARK_DB_PASSWORD:-edbarchive}"

run_directory="/results/${run_id}"
summary_file="${run_directory}/summary.csv"
mkdir -p "${run_directory}"
printf '%s\n' \
    'scenario,method,backup_backend_ms,backup_total_ms,restore_backend_ms,restore_total_ms,dump_bytes,bundle_bytes' \
    > "${summary_file}"

methods=(baseline carpov erkin edbarchive)
case "${selected_scenario}" in
    district)
        scenario_names=(district)
        scenario_codes=(district)
        scenario_configs=(/configs/district.json)
        ;;
    district-customer-item)
        scenario_names=(district-customer-item)
        scenario_codes=(dci)
        scenario_configs=(/configs/district-customer-item.json)
        ;;
    all)
        scenario_names=(district district-customer-item)
        scenario_codes=(district dci)
        scenario_configs=(/configs/district.json /configs/district-customer-item.json)
        ;;
esac

for scenario_index in "${!scenario_names[@]}"; do
    scenario="${scenario_names[scenario_index]}"
    scenario_code="${scenario_codes[scenario_index]}"
    config_file="${scenario_configs[scenario_index]}"

    for method in "${methods[@]}"; do
        result_name="${scenario}-${method}"
        result_directory="${run_directory}/${result_name}"
        restored_database="benchmark_${run_id}_${scenario_code}_${method}"

        echo
        echo "============================================================"
        echo "Scenario: ${scenario}; method: ${method}"
        echo "============================================================"

        backup_arguments=(
            --method "${method}"
            --source-db "${source_db}"
            --config "${config_file}"
            --context "${context_file}"
            --public-key "${key_directory}/public.bin"
            --private-key "${key_directory}/private.bin"
            --name "${result_name}"
            --results-dir "${run_directory}"
        )
        run-backup.sh "${backup_arguments[@]}"

        restore_arguments=(
            --method "${method}"
            --bundle "${result_directory}/bundle.tar.gz"
            --database "${restored_database}"
            --metrics "${result_directory}/restore-metrics.json"
            --discard-bundle
        )
        if [[ "${method}" == "carpov" || "${method}" == "erkin" ]]; then
            restore_arguments+=(--key-dir "${key_directory}")
        fi
        run-restore.sh "${restore_arguments[@]}"

        jq -r \
            --arg scenario "${scenario}" \
            --arg method "${method}" \
            --slurpfile restore "${result_directory}/restore-metrics.json" \
            '[
                $scenario,
                $method,
                .backend_elapsed_ms,
                .total_elapsed_ms,
                $restore[0].backend_elapsed_ms,
                $restore[0].total_elapsed_ms,
                .dump_bytes,
                .bundle_bytes
            ] | @csv' \
            "${result_directory}/backup-metrics.json" >> "${summary_file}"

        if [[ "${keep_databases}" -eq 0 ]]; then
            mariadb -h "${db_host}" -P "${db_port}" -u "${db_user}" \
                -e "DROP DATABASE \`${restored_database}\`"
        fi
    done
done

echo
echo "All benchmark scenarios completed."
echo "Results: ${run_directory}"
echo "Summary: ${summary_file}"
